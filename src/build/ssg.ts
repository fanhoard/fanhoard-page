/**
 * ssg.ts - FanHoard Production SSG Orchestrator
 *
 * Generates static HTML pages for each language from source HTML + translation JSON.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { flattenJson } from './marker-parser';
import { transformHtml, setConfig, BuildConfig } from './html-transformer';
import {
  findHtmlFiles,
  copyDir,
  ensureDir,
  writeFile,
  loadTranslationFile,
  loadDbJson,
} from './file-utils';
import { generateSitemap } from './sitemap';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT = path.resolve(__dirname, '../..');

export const CONFIG: BuildConfig = {
  srcDir: ROOT,
  distDir: path.join(ROOT, 'dist'),
  assetsDir: 'assets',
  dbJsonPath: path.join(ROOT, 'assets/lang/options/db.json'),
  translationPath: (lang: string) => path.join(ROOT, `assets/lang/${lang}.json`),
  defaultLang: 'en',
  excludeDirs: [
    'dist',
    'node_modules',
    '.git',
    'scripts',
    'src',
    '.cloudflare',
    'google6b646fa60e0f9f2f.html',
    'index.html',
  ],
  removeScriptPatterns: [
    'lang-proxy.js',
    'lang-sync.js',
    'lang-coordinator.js',
  ],
  baseUrl: 'https://fanhoard.pages.dev',
  staticFiles: [
    'robots.txt',
    'sitemap.xml',
    '_headers',
    'google6b646fa60e0f9f2f.html',
    'console.css',
    'console.js',
    'console.html',
    'index.html',
  ],
  passThroughHiddenDirs: ['.well-known'],
  footerTemplatePath: path.join(ROOT, 'assets/template-html/footer-template.html'),
};

const args = process.argv.slice(2);
const DRY_RUN = args.includes('--dry-run');
const VERBOSE = args.includes('--verbose');

export function generateRedirects(langs: string[], passThroughDirs: string[]): string {
  const lines = [
    '# _redirects — generated by src/build/ssg.ts',
    '# DO NOT EDIT MANUALLY — edit src/build/ssg.ts to change redirect logic',
    '',
    '# ── Pass-through hidden dirs (domain verification, etc.) ────────────',
  ];

  for (const dir of passThroughDirs) {
    lines.push(`/${dir}/* /${dir}/:splat 200`);
  }

  lines.push(
    '',
    '# ── Static assets ───────────────────────────────────────────────────',
    '/assets/*    /assets/:splat    200',
    '/robots.txt  /robots.txt       200',
    '/sitemap.xml /sitemap.xml      200',
    '/favicon.ico /assets/images/fanhoard-hub360.ico 200',
    '',
    '# ── Language root -> home (REWRITE 200) ───────────────────',
  );

  for (const lang of langs) {
    lines.push(`/${lang}  /${lang}/home/ 200`);
    lines.push(`/${lang}/ /${lang}/home/ 200`);
  }

  lines.push(
    '',
    '# ── Language-specific pages (static HTML rewrite) ───────────────────',
  );

  for (const lang of langs) {
    lines.push(`/${lang}/* /${lang}/:splat 200`);
  }

  lines.push(
    '',
    '# ── Catch-all 404 ───────────────────────────────────────────────────',
    '/* /index.html 404',
    '',
  );

  return lines.join('\n');
}

export async function runSSG(): Promise<void> {
  const startTime = Date.now();
  console.log('');
  console.log('╔══════════════════════════════════════╗');
  console.log('║   FanHoard Static Build System v2.0  ║');
  console.log('║   (TypeScript SSG Pipeline)          ║');
  if (DRY_RUN) console.log('║   ⚠  DRY RUN — no files written       ║');
  console.log('╚══════════════════════════════════════╝');
  console.log('');

  // 1. Load language config
  const dbJson = loadDbJson(CONFIG.dbJsonPath);
  if (!dbJson) {
    console.error(`[build] ✗ Cannot find db.json at "${CONFIG.dbJsonPath}"`);
    process.exit(1);
  }

  const langs = Object.keys(dbJson);
  if (!langs.length) {
    console.error('[build] ✗ db.json has no language entries');
    process.exit(1);
  }

  console.log(`[config] Languages : ${langs.join(', ')}`);
  console.log(`[config] Default   : ${CONFIG.defaultLang}`);
  console.log(`[config] Output    : ${CONFIG.distDir}/`);
  console.log('');

  let footerHtml = '';
  if (CONFIG.footerTemplatePath && fs.existsSync(CONFIG.footerTemplatePath)) {
    footerHtml = fs.readFileSync(CONFIG.footerTemplatePath, 'utf8');
    console.log(`[footer]  Loaded footer template (${footerHtml.length} chars)`);
  } else {
    console.warn('[footer]  ⚠  footer-template.html not found — footer will not be baked in');
  }
  setConfig({ ...CONFIG, langs, footerHtml });

  // 2. Load translations
  const translations: Record<string, Record<string, string>> = {};
  for (const lang of langs) {
    const filePath = CONFIG.translationPath(lang);
    const data = loadTranslationFile(filePath, flattenJson as any);

    if (data === null) {
      if (lang === CONFIG.defaultLang && dbJson[lang]?.enSource !== 'json') {
        translations[lang] = {};
        console.log(`[trans]  ${lang.toUpperCase()} -> (HTML source, no JSON translation file)`);
      } else {
        console.error(`[build] ✗ Translation file missing: ${filePath}`);
        process.exit(1);
      }
    } else {
      translations[lang] = data;
      console.log(`[trans]  ${lang.toUpperCase()} -> ${Object.keys(data).length} keys loaded`);
    }
  }

  // 3. Find HTML files
  const htmlFiles = findHtmlFiles(CONFIG.srcDir, CONFIG.excludeDirs);
  console.log(`\n[scan]  Found ${htmlFiles.length} HTML file(s)\n`);

  if (!htmlFiles.length) {
    console.warn('[build] ⚠  No HTML files found. Check your project structure.');
    process.exit(0);
  }

  // 4. Transform & write
  if (!DRY_RUN) {
    ensureDir(CONFIG.distDir);
  }

  let totalPages = 0;
  let totalErrors = 0;

  for (const srcFile of htmlFiles) {
    const relPath = path.relative(CONFIG.srcDir, srcFile).replace(/\\/g, '/');
    const srcHtml = fs.readFileSync(srcFile, 'utf8');

    if (VERBOSE) process.stdout.write(`  [${relPath}]\n`);

    for (const lang of langs) {
      const isDefaultWithHtmlSource =
        lang === CONFIG.defaultLang &&
        !Object.keys(translations[lang]).length &&
        dbJson[lang]?.enSource !== 'json';

      let builtHtml: string;
      try {
        if (isDefaultWithHtmlSource) {
          builtHtml = transformHtml(srcHtml, lang, {}, relPath, dbJson);
        } else {
          builtHtml = transformHtml(srcHtml, lang, translations[lang], relPath, dbJson);
        }
      } catch (err: any) {
        console.error(`    ✗ Error transforming [${lang}] ${relPath}:`, err.message);
        if (VERBOSE) console.error(err.stack);
        totalErrors++;
        continue;
      }

      const outPath = path.join(CONFIG.distDir, lang, relPath);
      if (!DRY_RUN) {
        writeFile(outPath, builtHtml);
      }

      if (VERBOSE) process.stdout.write(`    ✓ ${lang}  ->  ${path.join(lang, relPath)}\n`);
      totalPages++;
    }
  }

  // 5. Copy assets
  if (!DRY_RUN) {
    console.log('[assets] Copying assets/...');
    const srcAssets = path.join(CONFIG.srcDir, CONFIG.assetsDir);
    const destAssets = path.join(CONFIG.distDir, CONFIG.assetsDir);
    copyDir(srcAssets, destAssets);

    // 6. Copy static files
    for (const file of CONFIG.staticFiles) {
      const src = path.join(CONFIG.srcDir, file);
      const dest = path.join(CONFIG.distDir, file);
      if (fs.existsSync(src)) {
        ensureDir(path.dirname(dest));
        fs.copyFileSync(src, dest);
        console.log(`[assets] Copied ${file}`);
      }
    }

    // 7. Copy hidden pass-through directories
    for (const dir of CONFIG.passThroughHiddenDirs) {
      const src = path.join(CONFIG.srcDir, dir);
      const dest = path.join(CONFIG.distDir, dir);
      if (fs.existsSync(src)) {
        copyDir(src, dest);
        console.log(`[assets] Copied hidden dir ${dir}/`);
      }
    }

    // 8. Generate _redirects
    const redirectsContent = generateRedirects(langs, CONFIG.passThroughHiddenDirs);
    writeFile(path.join(CONFIG.distDir, '_redirects'), redirectsContent);
    console.log('\n[redirects] Generated _redirects');

    // 9. Sitemap generation
    console.log('\n[sitemap] Generating sitemap.xml...');
    generateSitemap();
    const sitemapSrc = path.join(CONFIG.srcDir, 'sitemap.xml');
    const sitemapDest = path.join(CONFIG.distDir, 'sitemap.xml');
    if (fs.existsSync(sitemapSrc)) {
      fs.copyFileSync(sitemapSrc, sitemapDest);
      console.log('[sitemap] Copied sitemap.xml to dist/');
    }
  }

  const elapsed = ((Date.now() - startTime) / 1000).toFixed(2);
  console.log('\n─────────────────────────────────────────');
  if (totalErrors > 0) {
    console.log(`✗ Build completed with ${totalErrors} error(s)`);
  } else {
    console.log('✓ SSG Build successful');
  }
  console.log(`  ${totalPages} page(s) × ${langs.length} language(s) in ${elapsed}s`);
  if (!DRY_RUN) {
    console.log(`  Output: ./${path.relative(ROOT, CONFIG.distDir)}/`);
  }
  console.log('─────────────────────────────────────────\n');

  if (totalErrors > 0) process.exit(1);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  runSSG().catch((err) => {
    console.error('\n[build] ✗ Fatal error:', err.message);
    process.exit(1);
  });
}
